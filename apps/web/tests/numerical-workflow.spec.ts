import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("owner executes a numerical graph node and exports actual measurements and source artifact", async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  const sample = JSON.parse(await readFile(new URL("../../../examples/cli/node.json", import.meta.url), "utf8"));
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/projects");
  await page.getByRole("button", { name: "New research project", exact: true }).click();
  const form = page.getByRole("dialog");
  await form.getByLabel("Project name").fill(`Numerical acceptance ${Date.now()}`);
  await form.getByLabel("Research question").fill("Measure trapezoidal integration error for x² on [0, 1] with 5,000 intervals.");
  await form.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page).toHaveURL(/\/projects\/[^/]+\/workspace/);
  const projectId = new URL(page.url()).pathname.split("/")[2];
  try {
    // Explicit operational profile is isolated test setup; it does not assert publication readiness.
    const project = await (await request.get(`/api/projects/${projectId}`)).json();
    expect((await request.patch(`/api/projects/${projectId}`, { data: { expected_revision: project.revision, mode: "manual", config: { ...project.config, publication_profile: { id: "operational" } } } })).ok()).toBeTruthy();
    await page.reload();
    await expect(page.locator(".canvas-legend")).toContainText(`rev ${project.revision + 1}`);
    await page.locator(".workspace-toolbar").getByRole("button", { name: "Add node", exact: true }).click();
    await page.getByRole("dialog").getByLabel("Node type").selectOption("experiment");
    await page.getByRole("dialog").getByLabel("Node title").fill(sample.title);
    await page.getByRole("dialog").getByLabel("Instructions").fill(sample.instructions);
    await page.getByRole("dialog").getByRole("button", { name: "Create node", exact: true }).click();
    const inspector = page.locator(".inspector");
    await inspector.getByRole("tab", { name: "Config", exact: true }).click();
    await page.getByLabel("Agent / model / tools / budget / parameters").fill(JSON.stringify(sample.config));
    const saved = page.waitForResponse((response) => response.request().method() === "POST" && response.url().endsWith(`/api/projects/${projectId}/graph/commands`));
    await inspector.getByRole("button", { name: "Save changes", exact: true }).click();
    expect((await saved).ok()).toBeTruthy();
    const graph = await (await request.get(`/api/projects/${projectId}/graph`)).json();
    const node = graph.nodes.find((value: { title: string }) => value.title === sample.title);
    const submission = page.waitForResponse((response) => response.request().method() === "POST" && response.url().endsWith(`/api/nodes/${node.id}/run`));
    await page.locator(".workspace-toolbar").getByRole("button", { name: "Run node", exact: true }).click();
    const submitted = await (await submission).json();
    const runId = submitted.id || submitted.run_ids?.[0] || submitted.runs?.[0]?.id;
    expect(runId).toBeTruthy();
    await expect.poll(async () => (await (await request.get(`/api/runs/${runId}`)).json()).status, { timeout: 45000 }).toBe("completed");
    const run = await (await request.get(`/api/runs/${runId}`)).json();
    expect(run.node_id).toBe(node.id);
    expect(run.node_revision).toBe(node.revision);
    expect(run.metrics.intervals).toBe(5000);
    expect(run.metrics.integral).toBeCloseTo(1 / 3 + 1 / (6 * 5000 ** 2), 14);
    expect(run.metrics.absolute_error).toBeLessThan(1e-8);
    await page.goto(`/projects/${projectId}/runs?run=${runId}`);
    await expect(page.locator(".run-output")).toContainText('"intervals": 5000');
    await expect(page.locator(".run-output")).toContainText(String(run.metrics.integral));
    await page.reload();
    await expect(page.locator(".run-output")).toContainText('"intervals": 5000');
    const verification = await (await request.get(`/api/runs/${runId}/verification`)).json();
    expect(verification.verification_status).toBe("unverified");
    await page.goto(`/projects/${projectId}/data`);
    const csvEvent = page.waitForEvent("download", { timeout: 15000 });
    await page.getByRole("button", { name: "Export CSV", exact: true }).click();
    const csv = await csvEvent;
    const csvText = await readFile((await csv.path())!, "utf8");
    expect(csvText).toContain(runId);
    expect(csvText).toContain(String(run.metrics.integral));
    await page.goto(`/projects/${projectId}/files`);
    await page.getByLabel("Find files…").fill("metrics.json");
    const artifact = page.locator(".file-tree").getByRole("button", { name: /metrics\.json/ }).first();
    await expect(artifact).toBeVisible();
    await artifact.click();
    const artifactEvent = page.waitForEvent("download", { timeout: 15000 });
    await page.locator(".file-editor").getByRole("button", { name: "Download", exact: true }).click();
    const downloaded = await artifactEvent;
    const actualMetrics = JSON.parse(await readFile((await downloaded.path())!, "utf8"));
    expect(actualMetrics).toEqual(expect.objectContaining(run.metrics));
    await page.goto(`/projects/${projectId}/overview`);
    const exportEvent = page.waitForEvent("download", { timeout: 15000 });
    await page.getByRole("button", { name: "Export project", exact: true }).click();
    const archive = await exportEvent;
    const bytes = await readFile((await archive.path())!);
    expect(bytes.subarray(0, 2).toString()).toBe("PK");
    await testInfo.attach("actual-numerical-run", { body: JSON.stringify({ projectId, nodeId: node.id, runId, nodeRevision: run.node_revision, metrics: actualMetrics, verification, outputPath: run.output_path }, null, 2), contentType: "application/json" });
    expect(errors).toEqual([]);
  } finally { await request.delete(`/api/projects/${projectId}`); }
});
